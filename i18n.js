(function () {
  function detectDefaultLang() {
    var saved = localStorage.getItem("lang");
    if (saved === "fr" || saved === "en") return saved;
    return (navigator.language || "fr").toLowerCase().startsWith("en") ? "en" : "fr";
  }

  window.getLang = function () {
    return document.documentElement.getAttribute("lang") === "en" ? "en" : "fr";
  };

  window.t = function (key) {
    var lang = window.getLang();
    return (I18N[lang] && I18N[lang][key] !== undefined) ? I18N[lang][key] : key;
  };

  function decodeEntities(str) {
    var el = document.createElement("textarea");
    el.innerHTML = str;
    return el.value;
  }

  window.applyLang = function (lang) {
    var dict = I18N[lang] || I18N.fr;
    document.documentElement.setAttribute("lang", lang);
    localStorage.setItem("lang", lang);

    document.title = decodeEntities(dict["meta.title"]);
    var metaDesc = document.querySelector('meta[name="description"]');
    if (metaDesc) metaDesc.setAttribute("content", decodeEntities(dict["meta.description"]));

    document.querySelectorAll("[data-i18n]").forEach(function (el) {
      var key = el.getAttribute("data-i18n");
      if (dict[key] !== undefined) el.textContent = decodeEntities(dict[key]);
    });

    document.querySelectorAll("[data-i18n-html]").forEach(function (el) {
      var key = el.getAttribute("data-i18n-html");
      if (dict[key] !== undefined) el.innerHTML = dict[key];
    });

    document.querySelectorAll("[data-i18n-placeholder]").forEach(function (el) {
      var key = el.getAttribute("data-i18n-placeholder");
      if (dict[key] !== undefined) el.setAttribute("placeholder", decodeEntities(dict[key]));
    });

    document.querySelectorAll("[data-i18n-aria]").forEach(function (el) {
      var key = el.getAttribute("data-i18n-aria");
      if (dict[key] !== undefined) el.setAttribute("aria-label", decodeEntities(dict[key]));
    });

    // Bouton de bascule thème : libellé selon le thème courant
    var themeToggle = document.getElementById("theme-toggle");
    if (themeToggle) {
      var isDark = document.documentElement.getAttribute("data-theme") === "dark";
      themeToggle.setAttribute("aria-label", isDark ? dict["theme.enableLight"] : dict["theme.enableDark"]);
    }

    // Bouton de langue : affiche la langue cible
    var langToggle = document.getElementById("lang-toggle");
    if (langToggle) {
      langToggle.textContent = dict["lang.toggleLabel"];
      langToggle.setAttribute("aria-label", dict["lang.toggleAria"]);
    }
  };

  // Applique la langue avant le rendu (anti-flash), comme pour le thème
  window.__initialLang = detectDefaultLang();
  document.documentElement.setAttribute("lang", window.__initialLang);

  document.addEventListener("DOMContentLoaded", function () {
    window.applyLang(window.__initialLang);

    var langToggle = document.getElementById("lang-toggle");
    if (langToggle) {
      langToggle.addEventListener("click", function () {
        var next = window.getLang() === "fr" ? "en" : "fr";
        window.applyLang(next);
      });
    }
  });
})();
